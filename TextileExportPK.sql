-- ====================================
--  Queries
-- ====================================

select fiscal_year, sum(export_value_usd) as total_exports
from exports 
group by fiscal_year
order by fiscal_year;


select e.fiscal_year, p.category, sum(e.export_value_usd) as total_exports
from exports as e 
join products as p on p.product_id = e.product_id
group by e.fiscal_year, p.category;


select p.product_name, sum(e.export_value_usd) as total_exports
from exports as e 
join products as p on p.product_id = e.product_id
group by   p.product_name
order by  total_exports desc;

select c.country_name, c.region, sum(e.export_value_usd) as total_exports
from exports as e 
join countries as c on c.country_id = e.country_id
group by c.country_name, c.region
order by  total_exports DESC;

